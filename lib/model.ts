// Token Radar's value model: one sealed snapshot in, one ranked board out.
//
// The board ranks protocols that record no token yet. It covers every slug in the
// snapshot's watchlist (the floor, never a ceiling) and adds the early radar: the
// pre-token protocols below the watchlist floor with the strongest implied value,
// so a fast-growing small protocol is found early instead of waiting for its TVL
// to cross the floor. Protocols whose token already trades are kept apart and
// shown with the market's own market cap, never mixed into the ranking.
//
// Implied value is one formula of the snapshot's own figures, applied the same
// way to every protocol. No name is ever special-cased.
//
//   sector    = a FDV/TVL multiple for the protocol's sector, from its category
//   base      = tvl_usd x sector
//   growth    = clamp(change_7d, -50, 200) per cent
//   growthMult= 1 + (growth / 100) x GROWTH_WEIGHT
//   age       = days from listed_at to the snapshot's as_of (unknown: 365)
//   maturity  = 0.65 + min(age, 1460) / 1460 x 0.55
//   breadth   = 1 + 0.02 x min(chains, 8)
//   implied   = round(base x growthMult x maturity x breadth)
//
// Why each factor: the sector multiple is what new launches in that sector have
// actually been valued at relative to the value they secure; growth is the
// protocol's momentum over the last week; maturity is the patience premium, a
// protocol that has run longer with no token has more pent-up launch value; and
// breadth is reach, a protocol live on more chains has more users to reward.
// Confidence is data completeness only: it never moves the value, it says how
// much of the record the model could see.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may move them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 200,
  maturity_floor: 0.65,
  maturity_range: 0.55,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_per_chain: 0.02,
  breadth_max_chains: 8,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live token view carries, by market cap. */
